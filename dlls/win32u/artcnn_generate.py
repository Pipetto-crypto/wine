#!/usr/bin/env python3
"""Extract the original ArtCNN C4F16 weights and embed validated Vulkan shaders.

Run with Python 3, glslangValidator 12.0.0, and spirv-val from SPIRV-Tools
2023.1 on PATH. Pass --check to verify the committed header byte-for-byte.
The compiler version is relevant for exact reproduction of the SPIR-V.
"""

import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tempfile


HERE = Path(__file__).resolve().parent
UPSTREAM = 'https://github.com/Artoriuz/ArtCNN/blob/a1b6ace035df4a9e9a113713dd7ee4eb92dd67ea/GLSL/ArtCNN_C4F16.glsl'
MODEL_SHA256 = '03d0b3d31cb82c898a94a46663021a3e8f02c5a21d69c5cfdf0208de4bfd453e'
STAGES = [f'conv{i}' for i in range(7)] + ['reconstruct']


def make_weights(model):
    # Keep all upstream weights, matrix column order, and addition order intact.
    # Only the convolution bodies are reused; tile load, bounds checking, and
    # the surrounding mpv hook have been replaced in the Vulkan wrapper.
    blocks = re.split(r'^//!DESC ArtCNN C4F16 \(', model, flags=re.MULTILINE)
    expected = ('Conv2D', *(f'Conv2D-{i}-ReLU' for i in range(1, 5)),
                'Conv2D-5', 'Conv2D-6', 'Depth-To-Space')
    if [block.split(')', 1)[0] for block in blocks[1:]] != list(expected):
        raise ValueError('unexpected ArtCNN model stage list')

    parts = []
    for stage, block in enumerate(blocks[1:-1]):
        body = block.split('    barrier();\n', 1)[1].strip('\n').removesuffix('\n}')
        body = re.sub(r'\b(?:V4|M4|F)\b',
                      lambda m: {'V4': 'vec4', 'M4': 'mat4', 'F': 'float'}[m[0]], body)
        body = body.replace('ivec2(gl_GlobalInvocationID)', 'p')
        if len(re.findall(r'result[0-3] \+=', body)) != (144 if 1 <= stage <= 5 else 36):
            raise ValueError(f'unexpected number of ArtCNN convolution taps in stage {stage}')
        parts.append(f'#if ARTCNN_STAGE == {stage}\n'
                     'void convolve(ivec2 local_xy, ivec2 p)\n{\n'
                     f'{body}\n}}\n#endif\n')
    return '\n'.join(parts)


def embed_shader(work, stage, name):
    binary = work / f'{name}.spv'
    subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0',
                    '-Os', '-g0', f'-DARTCNN_STAGE={stage}', '-o', binary,
                    'artcnn.comp'], cwd=work, check=True)
    subprocess.run(['spirv-val', '--target-env', 'vulkan1.0', binary], check=True)
    words = [word for (word,) in struct.iter_unpack('<I', binary.read_bytes())]
    lines = ['    ' + ', '.join(f'0x{word:08x}' for word in words[i:i + 8]) + ','
             for i in range(0, len(words), 8)]
    return f'static const uint32_t artcnn_{name}_comp_spv[] =\n{{\n' + '\n'.join(lines) + '\n};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare with the committed header')
    args = parser.parse_args()
    source = (HERE / 'artcnn_c4f16.glsl').read_bytes()
    if hashlib.sha256(source).hexdigest() != MODEL_SHA256:
        parser.error('the vendored ArtCNN C4F16 shader does not match the pinned upstream source')
    model = source.decode('utf-8')
    notice = [line.removeprefix('//').removeprefix(' ') for line in model.split('//!', 1)[0].strip().splitlines()]
    header = ['/*', ' * Generated by artcnn_generate.py; do not edit.', f' * Source: {UPSTREAM}', ' *',
              *(f' * {line}' if line else ' *' for line in notice), ' */',
              '#ifndef __WINE_WIN32U_ARTCNN_SPV_H', '#define __WINE_WIN32U_ARTCNN_SPV_H',
              '', '#include <stdint.h>', '']
    with tempfile.TemporaryDirectory(prefix='artcnn-') as temp:
        work = Path(temp)
        (work / 'artcnn.comp').write_bytes((HERE / 'artcnn.comp').read_bytes())
        (work / 'artcnn_weights.glsl').write_bytes(make_weights(model).encode('utf-8'))
        for stage, name in enumerate(STAGES):
            header.append(embed_shader(work, stage, name))
    header.extend(['#endif', ''])
    data = '\n'.join(header).encode('utf-8')
    output = HERE / 'artcnn_spv.h'
    if args.check:
        if not output.is_file() or output.read_bytes() != data:
            parser.error('artcnn_spv.h is out of date (or was generated with a different compiler)')
    else:
        output.write_bytes(data)


if __name__ == '__main__':
    main()
